"""Evaluation framework: run the experiment suite and write a report.

    python -m ffr experiment            # everything (about 3 minutes on 16 cores)
    python -m ffr experiment --quick    # reduced sweeps (about 30 s)
    python -m ffr experiment srlg flapping --out results/

Outputs ``<out>/<experiment>.csv`` (raw rows), ``<out>/*.png`` (figures) and
``<out>/REPORT.md`` (tables + figures + one-line takeaways).
"""

from __future__ import annotations

import os
import time

from . import plots
from .runner import write_csv
from .suite import ALL, Experiment


def _table(rows: list[dict], cols: list[str] | None = None) -> str:
    if not rows:
        return "_no data_\n"
    cols = cols or list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


SUMMARY_COLS = ["topo", "app", "runs", "survival_pct", "dead_flows", "lost_pkts",
                "mean_outage_ms", "max_outage_ms", "stretch", "affected_flows",
                "peak_flow_entries", "looped_pkts", "max_link_flows_before",
                "max_link_flows_after"]
COLS = {
    "gap": ["topo", "app", "gap_ms", "runs", "survival_pct", "dead_flows", "lost_pkts",
            "mean_outage_ms"],
    "flapping_long": ["pattern", "app", "runs", "survival_pct", "lost_pkts", "mean_outage_ms",
                      "max_outage_ms", "stretch", "looped_pkts", "peak_flow_entries"],
    "risk_dynamic": ["topo", "app", "runs", "survival_pct", "affected_flows", "lost_pkts",
                     "mean_outage_ms", "mean_path_delay_ms", "stretch"],
    "srlg_followup": ["topo", "app", "runs", "survival_pct", "affected_flows", "lost_pkts",
                      "mean_outage_ms", "stretch"],
}


def figures(exp: Experiment, out: str) -> list[str]:
    s = exp.summary
    if exp.name == "timeline":
        return [plots.timeline(exp, out)]
    if exp.name in ("single_link", "node_crash", "srlg", "sequential", "flapping"):
        return [
            plots.grouped_bars(s, "lost_pkts", "packets lost per failure (symlog)",
                               f"{exp.title}: packets lost", out, f"{exp.name}_lost.png", log=True),
            plots.grouped_bars(s, "survival_pct", "% of failures with no dead flow",
                               f"{exp.title}: survival", out, f"{exp.name}_survival.png"),
        ]
    if exp.name == "gray":
        rows = [{**r, "app": r["config"].split()[0]} for r in s]
        return [plots.config_bars(rows, "config", "mean_outage_ms", "mean outage (ms)",
                                  "Gray failures: outage per detection setup", out,
                                  "gray_outage.png")]
    if exp.name == "bfd_tradeoff":
        return [
            plots.line(s, "bfd_interval_ms", "mean_outage_ms", "BFD interval (ms)",
                       "mean outage (ms)", "BFD: detection speed", out, "bfd_outage.png",
                       logx=True),
            plots.line(s, "bfd_interval_ms", "bfd_pkts_per_s_per_link", "BFD interval (ms)",
                       "hello packets / s / link", "BFD: overhead", out, "bfd_overhead.png",
                       logx=True),
        ]
    if exp.name == "state":
        return [plots.grouped_bars(s, "flow_entries", "flow entries (all switches)",
                                   "State: flow entries", out, "state_flows.png", log=True)]
    if exp.name == "risk_tradeoff":
        return [plots.tradeoff(s, out)]
    return []


def write_report(exps: list[Experiment], out: str, quick: bool, elapsed: float) -> str:
    lines = ["# Evaluation report", "",
             f"Generated by `python -m ffr experiment{' --quick' if quick else ''}` "
             f"in {elapsed:.0f} s. Traffic: all host pairs, constant bit rate; "
             "outage = longest run of consecutive lost packets. Raw data: the CSV files "
             "next to this report.", ""]
    for exp in exps:
        lines += [f"## {exp.title}", "", exp.question, ""]
        cols = SUMMARY_COLS if exp.summary and "survival_pct" in exp.summary[0] else None
        if exp.name == "gray":
            cols = ["config"] + SUMMARY_COLS[2:]
        cols = COLS.get(exp.name, cols)
        lines.append(_table(exp.summary, cols))
        for fig in exp.extra.get("figures", []):
            if fig:
                lines.append(f"![{exp.title}]({fig})\n")
    path = os.path.join(out, "REPORT.md")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    return path


def run_suite(names: list[str] | None = None, quick: bool = False, out: str = "results",
              workers: int | None = None) -> list[Experiment]:
    os.makedirs(out, exist_ok=True)
    names = names or list(ALL)
    t0 = time.time()
    exps = []
    for name in names:
        print(f"[{name}] running...", flush=True)
        exp = ALL[name](quick=quick, workers=workers)
        write_csv(exp.rows, os.path.join(out, f"{name}.csv"))
        exp.extra["figures"] = figures(exp, out)
        exps.append(exp)
    path = write_report(exps, out, quick, time.time() - t0)
    print(f"report: {path}")
    return exps
